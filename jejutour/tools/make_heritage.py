coef_x = np.linalg.lstsq(A, np.array([c[0] for c in CTRL]), rcond=None)[0]
coef_y = np.linalg.lstsq(A, np.array([c[1] for c in CTRL]), rcond=None)[0]
def affine(lat, lng):
    v = np.array([lat, lng, 1]); return np.array([v @ coef_x, v @ coef_y])
RES = [np.array([px, py]) - affine(la, ln) for px, py, la, ln in CTRL]
def to_px(lat, lng):
    """손그림 지도라 직선 변환에 '가까운 기준점들의 오차'를 가중 평균으로 더해 보정"""
    w = []
    for _, _, la, ln in CTRL:
        d2 = ((lat - la) * 111) ** 2 + ((lng - ln) * 93) ** 2   # km²
        if d2 < 1e-6: return tuple(affine(lat, lng) + RES[len(w)])
        w.append(1 / d2)
    w = np.array(w); corr = (w[:, None] * np.array(RES)).sum(0) / w.sum()
    return tuple(affine(lat, lng) + corr)

